/**
 * Get the category for a trending word or hashtag.
 * @param {string} word - The word or hashtag name
 * @returns {string|null} The category name, or null if not found
 */
export function getTrendingCategory(word) {
  if (!word) return null;
  const key = word
    .toLowerCase()
    .trim()
    .replace(/^#/, '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
  return CATEGORIES[key] || null;
}
